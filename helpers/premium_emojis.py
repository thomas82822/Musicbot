# ── Markdown → HTML converter ────────────────────────────────────────────────

_TAG_RE = re.compile(
    r'(<(?:/?(?:b|i|a|code|pre|blockquote|tg-emoji|spoiler)(?:\s[^>]*)?|/?\w+)>)',
    re.IGNORECASE,
)


def _escape_outside_tags(html: str) -> str:
    """
    Escape & < > in TEXT nodes (outside our HTML tags).
    Runs AFTER markdown→HTML so we don't double-escape our own tags.
    """
    parts = _TAG_RE.split(html)
    result = []
    for i, part in enumerate(parts):
        if i % 2 == 1:
            result.append(part)
        else:
            result.append(part.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))
    return ''.join(result)


def md_to_html(text: str) -> str:
    """
    Convert Pyrogram Markdown → Telegram HTML + inject premium emojis (randomly).

    Handles: **bold**, __italic__/_italic_, `code`, ```pre```,
             [text](url), > blockquote, ||spoiler||, and all emoji mappings.
    """
    if not text or not isinstance(text, str):
        return text

    # Step 1: blockquotes
    lines = text.split('\n')
    processed: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('> ') or line == '>':
            bq: list[str] = []
            while i < len(lines) and (lines[i].startswith('> ') or lines[i] == '>'):
                bq.append(lines[i][2:] if lines[i].startswith('> ') else '')
                i += 1
            processed.append('\x00BQ_OPEN\x00' + '\n'.join(bq) + '\x00BQ_CLOSE\x00')
        else:
            processed.append(line)
            i += 1
    text = '\n'.join(processed)

    # Step 2: links [text](url)
    text = re.sub(
        r'\[([^\]]+)\]\((https?://[^\s)]+)\)',
        lambda m: f'<a href="{m.group(2)}">{m.group(1)}</a>',
        text,
    )

    # Step 3: code blocks ``` ... ```
    text = re.sub(r'```([^`]+?)```', lambda m: f'<pre>{m.group(1)}</pre>', text, flags=re.DOTALL)

    # Step 4: inline code ` ... `
    text = re.sub(r'`([^`\n]+?)`', lambda m: f'<code>{m.group(1)}</code>', text)

    # Step 5: bold+italic ***text***
    text = re.sub(r'\*\*\*(.+?)\*\*\*', r'<b><i>\1</i></b>', text, flags=re.DOTALL)

    # Step 6: bold **text**
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text, flags=re.DOTALL)

    # Step 7: italic __text__
    text = re.sub(r'__(.+?)__', r'<i>\1</i>', text, flags=re.DOTALL)

    # Step 8: italic _text_ (not inside words)
    text = re.sub(r'(?<![a-zA-Z0-9_\-])_([^_\n]+?)_(?![a-zA-Z0-9_\-])', r'<i>\1</i>', text)

    # Step 9: spoiler ||text|| — Telegram HTML uses <tg-spoiler>, not <spoiler>
    text = re.sub(r'\|\|(.+?)\|\|', r'<tg-spoiler>\1</tg-spoiler>', text, flags=re.DOTALL)

    # Step 10: restore blockquotes
    text = text.replace('\x00BQ_OPEN\x00', '<blockquote>').replace('\x00BQ_CLOSE\x00', '</blockquote>')

    # Step 11: HTML-escape bare &, <, > outside our tags
    text = _escape_outside_tags(text)

    # Step 12: inject premium emojis (random pool selection)
    text = _apply_premium_emojis(text)

    return text


